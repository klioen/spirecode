import { afterEach, describe, expect, it, vi } from "vitest";
import { terminalStream } from "./terminalStream";
import { attachTerminalSession, type ReplayTerminal } from "./terminalReplay";

class FakeTerminal implements ReplayTerminal {
  readonly writes: Array<{ data: string; done?: () => void }> = [];
  onDataCalls = 0;
  private dataListener?: (data: string) => void;

  write(data: string, done?: () => void): void {
    this.writes.push({ data, done });
  }

  onData(listener: (data: string) => void): { dispose(): void } {
    this.onDataCalls += 1;
    this.dataListener = listener;
    return {
      dispose: () => {
        if (this.dataListener === listener) this.dataListener = undefined;
      },
    };
  }

  completeWrite(index: number, generatedResponse?: string): void {
    if (generatedResponse) this.dataListener?.(generatedResponse);
    this.writes[index]?.done?.();
  }

  emitInput(data: string): void {
    this.dataListener?.(data);
  }
}

afterEach(() => terminalStream.close("t1"));

describe("terminal replay input gate", () => {
  it("does not forward xterm responses generated by replayed history", () => {
    terminalStream.push({
      type: "output",
      terminalId: "t1",
      data: "history-query",
    });
    const terminal = new FakeTerminal();
    const writePty = vi.fn();

    attachTerminalSession("t1", terminal, writePty, vi.fn());

    expect(terminal.writes.map(({ data }) => data)).toEqual(["history-query"]);
    terminal.completeWrite(0, "history-response");
    expect(writePty).not.toHaveBeenCalled();

    terminal.emitInput("keyboard-input");
    expect(writePty).toHaveBeenCalledWith("keyboard-input");
  });

  it("buffers live output in order and restores responses for live queries", () => {
    terminalStream.push({ type: "output", terminalId: "t1", data: "history" });
    const terminal = new FakeTerminal();
    const writePty = vi.fn();

    attachTerminalSession("t1", terminal, writePty, vi.fn());
    terminalStream.push({ type: "output", terminalId: "t1", data: "live-1" });
    terminalStream.push({ type: "output", terminalId: "t1", data: "live-2" });

    expect(terminal.writes.map(({ data }) => data)).toEqual(["history"]);
    terminal.completeWrite(0);
    expect(terminal.writes.map(({ data }) => data)).toEqual([
      "history",
      "live-1",
      "live-2",
    ]);

    terminal.completeWrite(1, "live-query-response");
    expect(writePty).toHaveBeenCalledWith("live-query-response");
  });

  it("preserves streaming UTF-8 decoding for output buffered during replay", () => {
    terminalStream.push({ type: "output", terminalId: "t1", data: "history" });
    const terminal = new FakeTerminal();

    attachTerminalSession("t1", terminal, vi.fn(), vi.fn());
    terminalStream.push({
      type: "output",
      terminalId: "t1",
      data: new Uint8Array([226]),
    });
    terminalStream.push({
      type: "output",
      terminalId: "t1",
      data: new Uint8Array([156, 147]),
    });
    terminal.completeWrite(0);

    expect(terminal.writes.map(({ data }) => data).join("")).toBe("history✓");
  });

  it("starts a fresh UTF-8 decoder when replaying after a remount", () => {
    terminalStream.push({
      type: "output",
      terminalId: "t1",
      data: new Uint8Array([226]),
    });
    const firstTerminal = new FakeTerminal();
    const firstSession = attachTerminalSession(
      "t1",
      firstTerminal,
      vi.fn(),
      vi.fn(),
    );
    firstTerminal.completeWrite(0);
    firstSession.dispose();

    const remountedTerminal = new FakeTerminal();
    attachTerminalSession("t1", remountedTerminal, vi.fn(), vi.fn());
    remountedTerminal.completeWrite(0);
    terminalStream.push({
      type: "output",
      terminalId: "t1",
      data: new Uint8Array([156, 147]),
    });

    expect(remountedTerminal.writes.map(({ data }) => data).join("")).toBe("✓");
  });

  it("does not register input or process buffered output after disposal", () => {
    terminalStream.push({ type: "output", terminalId: "t1", data: "history" });
    const terminal = new FakeTerminal();
    const writePty = vi.fn();
    const session = attachTerminalSession("t1", terminal, writePty, vi.fn());
    terminalStream.push({ type: "output", terminalId: "t1", data: "live" });

    session.dispose();
    terminal.completeWrite(0);
    terminal.emitInput("late-input");

    expect(terminal.writes.map(({ data }) => data)).toEqual(["history"]);
    expect(terminal.onDataCalls).toBe(0);
    expect(writePty).not.toHaveBeenCalled();
  });
});
